const quieto = matchMedia("(prefers-reduced-motion: reduce)");
const oscuro = matchMedia("(prefers-color-scheme: dark)");

/** Acercarse de a poco a un valor: k es la rapidez, dt los segundos que pasaron. */
export const hacia = (ahora, meta, k, dt) => ahora + (meta - ahora) * (1 - Math.exp(-k * dt));

/* ---------- los colores salen del CSS (base.css), así cambian solos con el modo oscuro ---------- */
export function color(nombre) {
  return getComputedStyle(document.documentElement).getPropertyValue(nombre).trim() || "#888888";
}
/** El color como tres números de 0 a 1, tal cual está escrito (para los shaders propios). */
export function colorCrudo(nombre) {
  const h = color(nombre).replace("#", "");
  return new THREE.Vector3(parseInt(h.slice(0, 2), 16) / 255, parseInt(h.slice(2, 4), 16) / 255, parseInt(h.slice(4, 6), 16) / 255);
}
export function alCambiarColores(fn) { oscuro.addEventListener("change", fn); }
export const esOscuro = () => oscuro.matches;
